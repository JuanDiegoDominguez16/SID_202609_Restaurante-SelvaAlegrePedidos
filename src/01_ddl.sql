-- =============================================================================
-- 1. TABLAS DE CATALOGO (SIN DEPENDENCIAS)
-- =============================================================================

-- ESTADOS DEL PEDIDO: ABIERTO, EN PREPARACION, ENTREGADO, PAGADO, CANCELADO.
CREATE TABLE ORDER_STATES (
    ID_ORDER_STATE  VARCHAR2(20) NOT NULL,
    NAME_STATE      VARCHAR2(20) NOT NULL,
    CONSTRAINT ORDER_STATES_PK PRIMARY KEY (ID_ORDER_STATE),
    CONSTRAINT ORDER_STATES__UN UNIQUE (NAME_STATE)
);

-- ESTADOS DE LA MESA: LIBRE U OCUPADA.
CREATE TABLE TABLES_STATES (
    ID_TABLE_STATE  VARCHAR2(20) NOT NULL,
    NAME_STATE      VARCHAR2(20) NOT NULL,
    CONSTRAINT TABLES_STATES_PK PRIMARY KEY (ID_TABLE_STATE),
    CONSTRAINT TABLES_STATES__UN UNIQUE (NAME_STATE)
);

-- CATEGORIAS DEL MENU. CADA PLATO PERTENECE A UNA SOLA CATEGORIA.
CREATE TABLE CATEGORY_PLATES (
    ID_CATEGORY    VARCHAR2(20) NOT NULL,
    NAME_CATEGORY  VARCHAR2(20) NOT NULL,
    CONSTRAINT CATEGORY_PLATES_PK PRIMARY KEY (ID_CATEGORY)
);


-- =============================================================================
-- 2. EMPLEADOS Y CLIENTES (SUPERTIPOS)
-- =============================================================================

-- EMPLEADOS DEL RESTAURANTE. ID_EMPLOYEE ES LA CEDULA.
CREATE TABLE EMPLOYEES (
    ID_EMPLOYEE  VARCHAR2(20) NOT NULL,
    NAME         VARCHAR2(20) NOT NULL,
    TELEPHONE    VARCHAR2(20) NOT NULL,
    DATE_HIRING  DATE         NOT NULL,
    CONSTRAINT EMPLOYEES_PK PRIMARY KEY (ID_EMPLOYEE)
);

-- CLIENTES QUE REALIZAN PEDIDOS (PERSONA NATURAL O JURIDICA).
CREATE TABLE CLIENTS (
    ID_CLIENT  VARCHAR2(20) NOT NULL,
    NAME       VARCHAR2(20) NOT NULL,
    TELEPHONE  VARCHAR2(20),
    EMAIL      VARCHAR2(50),
    CONSTRAINT CLIENT_PK PRIMARY KEY (ID_CLIENT)
);


-- =============================================================================
-- 3. MENU Y MESAS
-- =============================================================================

-- PLATOS DEL MENU. EL NOMBRE NO SE REPITE.
CREATE TABLE PLATES (
    ID_PLATE                     VARCHAR2(20)  NOT NULL,
    NAME_PLATE                   VARCHAR2(20)  NOT NULL,
    DESCRIPTION                  VARCHAR2(200) NOT NULL,
    PRICE                        NUMBER(10, 2) NOT NULL,
    CATEGORY_PLATES_ID_CATEGORY  VARCHAR2(20)  NOT NULL,
    CONSTRAINT PLATES_PK PRIMARY KEY (ID_PLATE),
    CONSTRAINT PLATES__UN UNIQUE (NAME_PLATE),
    CONSTRAINT PLATES_CATEGORY_FK FOREIGN KEY (CATEGORY_PLATES_ID_CATEGORY)
        REFERENCES CATEGORY_PLATES (ID_CATEGORY),
    CONSTRAINT PLATES_PRICE_CK CHECK (PRICE > 0)                    -- CK
);

-- MESAS DEL LOCAL: NUMERO, CAPACIDAD Y ESTADO (LIBRE / OCUPADA).
CREATE TABLE DINING_TABLES (
    ID_TABLE                      VARCHAR2(20) NOT NULL,
    TABLE_NUMBER                  VARCHAR2(30) NOT NULL,
    CAPACITY                      NUMBER(2)    NOT NULL,
    TABLES_STATES_ID_TABLE_STATE  VARCHAR2(20) NOT NULL,
    CONSTRAINT DINING_TABLES_PK PRIMARY KEY (ID_TABLE),
    CONSTRAINT DINING_TABLES__UN UNIQUE (TABLE_NUMBER),
    CONSTRAINT DINING_TABLES_STATE_FK FOREIGN KEY (TABLES_STATES_ID_TABLE_STATE)
        REFERENCES TABLES_STATES (ID_TABLE_STATE),
    CONSTRAINT DINING_TABLES_CAPACITY_CK CHECK (CAPACITY > 0)       -- CK
);


-- =============================================================================
-- 4. SUBTIPOS DE EMPLEADO Y DE CLIENTE
-- =============================================================================

-- MESEROS. TURNO DE TRABAJO: MAÑANA, TARDE O NOCHE.
-- SE USA 6 CHAR (NO 6 BYTES) PORQUE 'MAÑANA' LLEVA UNA Ñ.
CREATE TABLE WAITERS (
    EMPLOYEES_ID_EMPLOYEE  VARCHAR2(20)   NOT NULL,
    SHIFT                  VARCHAR2(6 CHAR) NOT NULL,
    CONSTRAINT WAITERS_PK PRIMARY KEY (EMPLOYEES_ID_EMPLOYEE),
    CONSTRAINT WAITERS_EMPLOYEES_FK FOREIGN KEY (EMPLOYEES_ID_EMPLOYEE)
        REFERENCES EMPLOYEES (ID_EMPLOYEE),
    CONSTRAINT WAITERS_SHIFT_CK CHECK (SHIFT IN ('mañana', 'tarde', 'noche'))  -- CK
);

-- CHEFS. TITULO, ESPECIALIDAD Y AÑOS DE EXPERIENCIA.
CREATE TABLE CHEFS (
    EMPLOYEES_ID_EMPLOYEE  VARCHAR2(20) NOT NULL,
    DEGREE                 VARCHAR2(20) NOT NULL,
    SPECIALTY              VARCHAR2(20) NOT NULL,
    YEARS_EXPERIENCE       NUMBER(2)    NOT NULL,
    CONSTRAINT CHEFS_PK PRIMARY KEY (EMPLOYEES_ID_EMPLOYEE),
    CONSTRAINT CHEFS_EMPLOYEES_FK FOREIGN KEY (EMPLOYEES_ID_EMPLOYEE)
        REFERENCES EMPLOYEES (ID_EMPLOYEE),
    CONSTRAINT CHEFS_YEARS_CK CHECK (YEARS_EXPERIENCE >= 0)         -- CK
);

-- CLIENTE PERSONA NATURAL: IDENTIFICADO CON SU CEDULA.
CREATE TABLE PERSON (
    CLIENT_ID_CLIENT  VARCHAR2(20) NOT NULL,
    ID_CC             VARCHAR2(15) NOT NULL,
    CONSTRAINT PERSON_PK PRIMARY KEY (CLIENT_ID_CLIENT),
    CONSTRAINT PERSON__UN UNIQUE (ID_CC),
    CONSTRAINT PERSON_CLIENTS_FK FOREIGN KEY (CLIENT_ID_CLIENT)
        REFERENCES CLIENTS (ID_CLIENT)
);

-- CLIENTE PERSONA JURIDICA: IDENTIFICADO CON EL NIT DE LA EMPRESA.
CREATE TABLE COMPANY (
    CLIENT_ID_CLIENT  VARCHAR2(20) NOT NULL,
    ID_NIT            VARCHAR2(20) NOT NULL,
    CONSTRAINT COMPANY_PK PRIMARY KEY (CLIENT_ID_CLIENT),
    CONSTRAINT COMPANY__UN UNIQUE (ID_NIT),
    CONSTRAINT COMPANY_CLIENTS_FK FOREIGN KEY (CLIENT_ID_CLIENT)
        REFERENCES CLIENTS (ID_CLIENT)
);


-- =============================================================================
-- 5. PEDIDOS Y DETALLE DE PEDIDOS
-- =============================================================================

-- PEDIDOS. CADA PEDIDO TIENE UNA MESA, UN CLIENTE, UN MESERO Y UN ESTADO.
-- EL TOTAL NO SE GUARDA: SE CALCULA CON LA SUMA DE SUS DETALLES.
CREATE TABLE RESTAURANT_ORDERS (
    ID_ORDER                      VARCHAR2(20) NOT NULL,
    DATE_TIME                     DATE         NOT NULL,
    ORDER_STATES_ID_ORDER_STATE   VARCHAR2(20) NOT NULL,
    CLIENT_ID_CLIENT              VARCHAR2(20) NOT NULL,
    DINING_TABLES_ID_TABLE        VARCHAR2(20) NOT NULL,
    WAITERS_EMPLOYEES_ID_EMPLOYEE VARCHAR2(20) NOT NULL,
    CONSTRAINT RESTAURANT_ORDERS_PK PRIMARY KEY (ID_ORDER),
    CONSTRAINT RESTAURANT_ORDERS_STATE_FK FOREIGN KEY (ORDER_STATES_ID_ORDER_STATE)
        REFERENCES ORDER_STATES (ID_ORDER_STATE),
    CONSTRAINT RESTAURANT_ORDERS_CLIENT_FK FOREIGN KEY (CLIENT_ID_CLIENT)
        REFERENCES CLIENTS (ID_CLIENT),
    CONSTRAINT RESTAURANT_ORDERS_TABLE_FK FOREIGN KEY (DINING_TABLES_ID_TABLE)
        REFERENCES DINING_TABLES (ID_TABLE),
    CONSTRAINT RESTAURANT_ORDERS_WAITER_FK FOREIGN KEY (WAITERS_EMPLOYEES_ID_EMPLOYEE)
        REFERENCES WAITERS (EMPLOYEES_ID_EMPLOYEE)
);

-- DETALLE DEL PEDIDO: UN PLATO PEDIDO, SU CANTIDAD Y EL PRECIO QUE TENIA
-- EN ESE MOMENTO. LA LLAVE ES COMPUESTA (PEDIDO + NUMERO DE DETALLE).
CREATE TABLE ORDER_DETAILS (
    RESTAURANT_ORDERS_ID_ORDER  VARCHAR2(20) NOT NULL,
    ID_DETAIL                   VARCHAR2(20) NOT NULL,
    QUANTITY                    NUMBER(4)    NOT NULL,
    UNIT_PRICE                  NUMBER(10, 2) NOT NULL,
    PLATES_ID_PLATE             VARCHAR2(20) NOT NULL,
    CONSTRAINT ORDER_DETAILS_PK PRIMARY KEY (RESTAURANT_ORDERS_ID_ORDER, ID_DETAIL),
    CONSTRAINT ORDER_DETAILS_ORDER_FK FOREIGN KEY (RESTAURANT_ORDERS_ID_ORDER)
        REFERENCES RESTAURANT_ORDERS (ID_ORDER),
    CONSTRAINT ORDER_DETAILS_PLATE_FK FOREIGN KEY (PLATES_ID_PLATE)
        REFERENCES PLATES (ID_PLATE),
    CONSTRAINT ORDER_DETAILS_QUANTITY_CK CHECK (QUANTITY > 0),      -- CK
    CONSTRAINT ORDER_DETAILS_PRICE_CK CHECK (UNIT_PRICE > 0)        -- CK
);


-- =============================================================================
-- 6. INDICES SOBRE LLAVES FORANEAS
-- ORACLE NO LOS CREA AUTOMATICAMENTE; ACELERAN LOS JOINS DE LOS REPORTES.
-- =============================================================================
CREATE INDEX PLATES_CATEGORY_IX         ON PLATES (CATEGORY_PLATES_ID_CATEGORY);
CREATE INDEX DINING_TABLES_STATE_IX     ON DINING_TABLES (TABLES_STATES_ID_TABLE_STATE);
CREATE INDEX RESTAURANT_ORDERS_STATE_IX ON RESTAURANT_ORDERS (ORDER_STATES_ID_ORDER_STATE);
CREATE INDEX RESTAURANT_ORDERS_CLIENT_IX ON RESTAURANT_ORDERS (CLIENT_ID_CLIENT);
CREATE INDEX RESTAURANT_ORDERS_TABLE_IX ON RESTAURANT_ORDERS (DINING_TABLES_ID_TABLE);
CREATE INDEX RESTAURANT_ORDERS_WAITER_IX ON RESTAURANT_ORDERS (WAITERS_EMPLOYEES_ID_EMPLOYEE);
CREATE INDEX RESTAURANT_ORDERS_DATE_IX  ON RESTAURANT_ORDERS (DATE_TIME);
CREATE INDEX ORDER_DETAILS_PLATE_IX     ON ORDER_DETAILS (PLATES_ID_PLATE);


