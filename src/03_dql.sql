-- DESCRIPCION:   CONSULTAS (DQL) DE LOS TRES REPORTES DEL CASO:
--                  1. PLATOS MAS VENDIDOS EN UN PERIODO (TOP N).
--                  2. VENTAS TOTALES POR DIA, SEMANA Y MES.
--                  3. DESEMPEÑO POR MESERO (PEDIDOS Y VALOR VENDIDO).
--                MAS DOS CONSULTAS COMPLEMENTARIAS (CLIENTES Y PEDIDOS EN CURSO).
-- PRERREQUISITO: 01_DDL.SQL Y 02_DML.SQL. LA CONSULTA 5 USA LA FUNCION
--                FN_TOTAL_PEDIDO (04A_FN_TOTAL_PEDIDO.SQL).
-- EJECUCION:     SQL DEVELOPER, F5 (EJECUTAR SCRIPT).
--
-- REGLAS COMUNES
--   * SOLO CUENTAN LOS PEDIDOS EN ESTADO 'pagado': UN PEDIDO ABIERTO O
--     CANCELADO NO ES UNA VENTA.
--   * EL VALOR DE UNA LINEA ES QUANTITY * UNIT_PRICE (PRECIO AL MOMENTO DEL
--     PEDIDO, NO EL PRECIO ACTUAL DEL MENU). EL TOTAL DE UN PEDIDO NO SE
--     GUARDA: SE CALCULA SUMANDO SUS DETALLES.
--   * EL PERIODO Y EL TOP SE CAMBIAN EN LAS VARIABLES DE ABAJO (DEFINE).
--     LA FECHA FINAL ES INCLUSIVE (SE INCLUYE TODO ESE DIA).
--   * EN ORACLE NO EXISTE "TOP N": SU EQUIVALENTE ES
--     FETCH FIRST N ROWS ONLY (ORACLE 12C O SUPERIOR).
--   * JOIN INTERNO (INNER): SOLO FILAS CON COINCIDENCIA EN AMBAS TABLAS.
--     JOIN EXTERNO (LEFT): CONSERVA LAS FILAS DE LA TABLA IZQUIERDA AUNQUE NO
--     TENGAN COINCIDENCIA (APARECEN CON NULL O CERO).
--   * CONSULTAS ESCRITAS CON AYUDA DE IA (CLAUDE); VER DOCS/BITACORA-PROMPTS.MD.
-- =============================================================================

SET VERIFY OFF
SET LINESIZE 200
SET PAGESIZE 100

-- PARAMETROS DE LOS REPORTES
DEFINE V_FECHA_INI = '2026-09-01'
DEFINE V_FECHA_FIN = '2026-11-30'
DEFINE V_TOP       = 5


-- =============================================================================
-- REPORTE 1. PLATOS MAS VENDIDOS EN UN PERIODO
-- =============================================================================

-- CONSULTA 1A (TOP N). LOS &V_TOP PLATOS CON MAS UNIDADES VENDIDAS ENTRE
-- &V_FECHA_INI Y &V_FECHA_FIN, CON SU CATEGORIA Y EL VALOR VENDIDO.
-- DE MAYOR A MENOR; SI HAY EMPATE, POR NOMBRE.
-- TABLAS: ORDER_DETAILS, RESTAURANT_ORDERS, ORDER_STATES, PLATES,
--         CATEGORY_PLATES (JOINS INTERNOS).
SELECT P.ID_PLATE,
       P.NAME_PLATE                      AS PLATO,
       C.NAME_CATEGORY                   AS CATEGORIA,
       SUM(D.QUANTITY)                   AS UNIDADES_VENDIDAS,
       SUM(D.QUANTITY * D.UNIT_PRICE)    AS VALOR_VENDIDO
  FROM ORDER_DETAILS D
  JOIN RESTAURANT_ORDERS O ON O.ID_ORDER = D.RESTAURANT_ORDERS_ID_ORDER
  JOIN ORDER_STATES S      ON S.ID_ORDER_STATE = O.ORDER_STATES_ID_ORDER_STATE
  JOIN PLATES P            ON P.ID_PLATE = D.PLATES_ID_PLATE
  JOIN CATEGORY_PLATES C   ON C.ID_CATEGORY = P.CATEGORY_PLATES_ID_CATEGORY
 WHERE S.NAME_STATE = 'pagado'
   AND O.DATE_TIME >= TO_DATE('&V_FECHA_INI', 'YYYY-MM-DD')
   AND O.DATE_TIME <  TO_DATE('&V_FECHA_FIN', 'YYYY-MM-DD') + 1
 GROUP BY P.ID_PLATE, P.NAME_PLATE, C.NAME_CATEGORY
 ORDER BY UNIDADES_VENDIDAS DESC, P.NAME_PLATE
 FETCH FIRST &V_TOP ROWS ONLY;

-- CONSULTA 1B (JOIN EXTERNO). RANKING COMPLETO DEL MENU EN EL PERIODO,
-- INCLUIDOS LOS PLATOS QUE NO SE VENDIERON (0 UNIDADES), PARA DECIDIR QUE
-- PLATOS AJUSTAR O RETIRAR. EL FILTRO DE ESTADO Y FECHA VA DENTRO DE LA
-- VISTA EN LINEA: SI VA EN EL WHERE EXTERIOR, EL JOIN EXTERNO PIERDE LOS
-- PLATOS SIN VENTAS.
-- TABLAS: PLATES (LEFT JOIN) ORDER_DETAILS + RESTAURANT_ORDERS + ORDER_STATES.
SELECT P.ID_PLATE,
       P.NAME_PLATE                          AS PLATO,
       NVL(SUM(V.QUANTITY), 0)               AS UNIDADES_VENDIDAS,
       NVL(SUM(V.QUANTITY * V.UNIT_PRICE), 0) AS VALOR_VENDIDO
  FROM PLATES P
  LEFT JOIN (SELECT D.PLATES_ID_PLATE, D.QUANTITY, D.UNIT_PRICE
               FROM ORDER_DETAILS D
               JOIN RESTAURANT_ORDERS O ON O.ID_ORDER = D.RESTAURANT_ORDERS_ID_ORDER
               JOIN ORDER_STATES S      ON S.ID_ORDER_STATE = O.ORDER_STATES_ID_ORDER_STATE
              WHERE S.NAME_STATE = 'pagado'
                AND O.DATE_TIME >= TO_DATE('&V_FECHA_INI', 'YYYY-MM-DD')
                AND O.DATE_TIME <  TO_DATE('&V_FECHA_FIN', 'YYYY-MM-DD') + 1) V
         ON V.PLATES_ID_PLATE = P.ID_PLATE
 GROUP BY P.ID_PLATE, P.NAME_PLATE
 ORDER BY UNIDADES_VENDIDAS DESC, P.NAME_PLATE;


-- =============================================================================
-- REPORTE 2. VENTAS TOTALES POR DIA, SEMANA Y MES
-- =============================================================================

-- CONSULTA 2A (POR DIA). PEDIDOS PAGADOS, VALOR VENDIDO Y TICKET PROMEDIO
-- (VALOR / PEDIDOS) DE CADA DIA DEL PERIODO, DEL MAS ANTIGUO AL MAS RECIENTE.
-- TRUNC(FECHA) QUITA LA HORA PARA AGRUPAR POR DIA.
SELECT TO_CHAR(TRUNC(O.DATE_TIME), 'YYYY-MM-DD')         AS DIA,
       COUNT(DISTINCT O.ID_ORDER)                        AS PEDIDOS,
       SUM(D.QUANTITY * D.UNIT_PRICE)                    AS VALOR_VENDIDO,
       ROUND(SUM(D.QUANTITY * D.UNIT_PRICE)
             / COUNT(DISTINCT O.ID_ORDER))               AS TICKET_PROMEDIO
  FROM RESTAURANT_ORDERS O
  JOIN ORDER_STATES S ON S.ID_ORDER_STATE = O.ORDER_STATES_ID_ORDER_STATE
  JOIN ORDER_DETAILS D ON D.RESTAURANT_ORDERS_ID_ORDER = O.ID_ORDER
 WHERE S.NAME_STATE = 'pagado'
   AND O.DATE_TIME >= TO_DATE('&V_FECHA_INI', 'YYYY-MM-DD')
   AND O.DATE_TIME <  TO_DATE('&V_FECHA_FIN', 'YYYY-MM-DD') + 1
 GROUP BY TRUNC(O.DATE_TIME)
 ORDER BY TRUNC(O.DATE_TIME);

-- CONSULTA 2B (POR SEMANA). LO MISMO AGRUPADO POR SEMANA; LA SEMANA SE
-- IDENTIFICA POR SU LUNES (TRUNC CON 'IW' = SEMANA ISO, QUE EMPIEZA EL LUNES).
SELECT TO_CHAR(TRUNC(O.DATE_TIME, 'IW'), 'YYYY-MM-DD')   AS SEMANA_DEL_LUNES,
       COUNT(DISTINCT O.ID_ORDER)                        AS PEDIDOS,
       SUM(D.QUANTITY * D.UNIT_PRICE)                    AS VALOR_VENDIDO,
       ROUND(SUM(D.QUANTITY * D.UNIT_PRICE)
             / COUNT(DISTINCT O.ID_ORDER))               AS TICKET_PROMEDIO
  FROM RESTAURANT_ORDERS O
  JOIN ORDER_STATES S ON S.ID_ORDER_STATE = O.ORDER_STATES_ID_ORDER_STATE
  JOIN ORDER_DETAILS D ON D.RESTAURANT_ORDERS_ID_ORDER = O.ID_ORDER
 WHERE S.NAME_STATE = 'pagado'
   AND O.DATE_TIME >= TO_DATE('&V_FECHA_INI', 'YYYY-MM-DD')
   AND O.DATE_TIME <  TO_DATE('&V_FECHA_FIN', 'YYYY-MM-DD') + 1
 GROUP BY TRUNC(O.DATE_TIME, 'IW')
 ORDER BY TRUNC(O.DATE_TIME, 'IW');

-- CONSULTA 2C (POR MES, CON TOTAL GENERAL). LO MISMO POR MES; ROLLUP AGREGA
-- AL FINAL UNA FILA CON EL TOTAL DE TODO EL PERIODO (EL MES SALE NULL, POR ESO
-- SE ROTULA 'TOTAL').
SELECT NVL(TO_CHAR(TRUNC(O.DATE_TIME, 'MM'), 'YYYY-MM'), 'TOTAL') AS MES,
       COUNT(DISTINCT O.ID_ORDER)                        AS PEDIDOS,
       SUM(D.QUANTITY * D.UNIT_PRICE)                    AS VALOR_VENDIDO
  FROM RESTAURANT_ORDERS O
  JOIN ORDER_STATES S ON S.ID_ORDER_STATE = O.ORDER_STATES_ID_ORDER_STATE
  JOIN ORDER_DETAILS D ON D.RESTAURANT_ORDERS_ID_ORDER = O.ID_ORDER
 WHERE S.NAME_STATE = 'pagado'
   AND O.DATE_TIME >= TO_DATE('&V_FECHA_INI', 'YYYY-MM-DD')
   AND O.DATE_TIME <  TO_DATE('&V_FECHA_FIN', 'YYYY-MM-DD') + 1
 GROUP BY ROLLUP (TRUNC(O.DATE_TIME, 'MM'))
 ORDER BY TRUNC(O.DATE_TIME, 'MM');   -- NULLS LAST POR DEFECTO: EL TOTAL VA AL FINAL


-- =============================================================================
-- REPORTE 3. DESEMPEÑO POR MESERO
-- =============================================================================

-- CONSULTA 3 (JOIN EXTERNO + RANKING). PARA CADA MESERO: TURNO, PEDIDOS
-- PAGADOS, VALOR VENDIDO Y PUESTO (RANK, 1 = QUIEN MAS VENDIO). LOS MESEROS SIN
-- PEDIDOS EN EL PERIODO TAMBIEN APARECEN (0 PEDIDOS Y 0 VENDIDO).
-- TABLAS: EMPLOYEES + WAITERS (JOIN INTERNO: UN MESERO ES UN EMPLEADO),
--         LEFT JOIN A LOS PEDIDOS PAGADOS Y A SUS DETALLES.
SELECT E.ID_EMPLOYEE,
       E.NAME                                   AS MESERO,
       W.SHIFT                                  AS TURNO,
       COUNT(DISTINCT PO.ID_ORDER)              AS PEDIDOS_ATENDIDOS,
       NVL(SUM(D.QUANTITY * D.UNIT_PRICE), 0)   AS VALOR_VENDIDO,
       RANK() OVER (ORDER BY NVL(SUM(D.QUANTITY * D.UNIT_PRICE), 0) DESC) AS PUESTO
  FROM EMPLOYEES E
  JOIN WAITERS W ON W.EMPLOYEES_ID_EMPLOYEE = E.ID_EMPLOYEE
  LEFT JOIN (SELECT O.ID_ORDER, O.WAITERS_EMPLOYEES_ID_EMPLOYEE AS ID_MESERO
               FROM RESTAURANT_ORDERS O
               JOIN ORDER_STATES S ON S.ID_ORDER_STATE = O.ORDER_STATES_ID_ORDER_STATE
              WHERE S.NAME_STATE = 'pagado'
                AND O.DATE_TIME >= TO_DATE('&V_FECHA_INI', 'YYYY-MM-DD')
                AND O.DATE_TIME <  TO_DATE('&V_FECHA_FIN', 'YYYY-MM-DD') + 1) PO
         ON PO.ID_MESERO = W.EMPLOYEES_ID_EMPLOYEE
  LEFT JOIN ORDER_DETAILS D ON D.RESTAURANT_ORDERS_ID_ORDER = PO.ID_ORDER
 GROUP BY E.ID_EMPLOYEE, E.NAME, W.SHIFT
 ORDER BY VALOR_VENDIDO DESC, E.NAME;


-- =============================================================================
-- CONSULTAS COMPLEMENTARIAS
-- =============================================================================

-- CONSULTA 4 (JOIN EXTERNO CON SUBTIPOS). CLIENTES CON SU TIPO (PERSONA NATURAL
-- O JURIDICA), SU DOCUMENTO Y CUANTOS PEDIDOS HAN HECHO; LOS CLIENTES SIN
-- PEDIDOS (EJ. C13) SALEN CON 0. PERSON Y COMPANY SE UNEN POR LEFT JOIN: UN
-- CLIENTE ESTA EN UNA SOLA DE LAS DOS.
SELECT C.ID_CLIENT,
       C.NAME                                          AS CLIENTE,
       CASE WHEN P.CLIENT_ID_CLIENT IS NOT NULL THEN 'persona natural'
            WHEN M.CLIENT_ID_CLIENT IS NOT NULL THEN 'persona juridica'
            ELSE 'sin tipo' END                        AS TIPO,
       NVL(P.ID_CC, M.ID_NIT)                          AS DOCUMENTO,
       COUNT(O.ID_ORDER)                               AS PEDIDOS
  FROM CLIENTS C
  LEFT JOIN PERSON P            ON P.CLIENT_ID_CLIENT = C.ID_CLIENT
  LEFT JOIN COMPANY M           ON M.CLIENT_ID_CLIENT = C.ID_CLIENT
  LEFT JOIN RESTAURANT_ORDERS O ON O.CLIENT_ID_CLIENT = C.ID_CLIENT
 GROUP BY C.ID_CLIENT, C.NAME, P.CLIENT_ID_CLIENT, M.CLIENT_ID_CLIENT, P.ID_CC, M.ID_NIT
 ORDER BY PEDIDOS DESC, C.NAME;

-- CONSULTA 5 (USA LA FUNCION FN_TOTAL_PEDIDO). PEDIDOS EN CURSO (ABIERTO, EN
-- PREPARACION O ENTREGADO) CON SU MESA, SU MESERO Y SU TOTAL ACTUAL, DEL MAS
-- RECIENTE AL MAS ANTIGUO. CUBRE LA HISTORIA DE USUARIO 5.
SELECT O.ID_ORDER,
       TO_CHAR(O.DATE_TIME, 'YYYY-MM-DD HH24:MI')  AS FECHA_HORA,
       S.NAME_STATE                                AS ESTADO,
       T.TABLE_NUMBER                              AS MESA,
       E.NAME                                      AS MESERO,
       FN_TOTAL_PEDIDO(O.ID_ORDER)                 AS TOTAL
  FROM RESTAURANT_ORDERS O
  JOIN ORDER_STATES S  ON S.ID_ORDER_STATE = O.ORDER_STATES_ID_ORDER_STATE
  JOIN DINING_TABLES T ON T.ID_TABLE = O.DINING_TABLES_ID_TABLE
  JOIN EMPLOYEES E     ON E.ID_EMPLOYEE = O.WAITERS_EMPLOYEES_ID_EMPLOYEE
 WHERE S.NAME_STATE IN ('abierto', 'en preparación', 'entregado')
 ORDER BY O.DATE_TIME DESC;

